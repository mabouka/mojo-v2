// Règles d'adresses recalculées une fois, la première fois que Types est
// désactivé (sinon elles restent celles enregistrées par Types). Réarmé tant que
// Types est actif, pour un retour arrière puis une nouvelle désactivation.
function mojo_flush_types_rewrite_rules()
{
    if (defined('TYPES_VERSION')) {
        if (get_option('mojo_types_rewrite_flushed')) delete_option('mojo_types_rewrite_flushed');
        return;
    }
    if (get_option('mojo_types_rewrite_flushed')) return;

    flush_rewrite_rules(false);
    update_option('mojo_types_rewrite_flushed', 1);
}

add_action('init', 'mojo_flush_types_rewrite_rules', 99);
